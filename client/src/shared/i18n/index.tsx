function normalizeLocale(value: unknown): Locale | null {
  if (typeof value !== 'string') return null;
  const normalized = value.toLowerCase().split(/[-_]/, 1)[0];
  return normalized === 'en' || normalized === 'vi' ? normalized : null;
}

function readDefaultLocale(): Locale {
  return normalizeLocale(import.meta.env.VITE_DEFAULT_LOCALE) ?? 'vi';
}

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return readDefaultLocale();
  return normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY)) ?? readDefaultLocale();
}

export function storeLocale(locale: Locale) {
  if (typeof window !== 'undefined') window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
}

export function translate(
  key: TranslationKey,
  locale: Locale = getStoredLocale(),
  fallback?: string,
  params?: TranslationParams,
) {
  const template = TRANSLATIONS[locale][key] ?? TRANSLATIONS.vi[key] ?? fallback ?? key;
  return params
    ? template.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match))
    : template;
}

